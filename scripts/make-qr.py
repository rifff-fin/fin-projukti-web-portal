"""
Encode the QR code printed on the Fin NFC card preview (sections/Nfc.tsx) as an SVG path,
so the site draws a real, scannable code without a QR library in the bundle.

    pip install segno
    python scripts/make-qr.py      # writes src/brand/qr.ts

Change URL below and re-run if the card should open somewhere else.
"""
from pathlib import Path

import segno

ROOT = Path(__file__).resolve().parent.parent
URL = 'https://finprojukti.tech/#nfc'

qr = segno.make(URL, error='m', micro=False)
rows = [[bool(v) for v in row] for row in qr.matrix]
size = len(rows)

# one horizontal run of dark modules = one rectangle
d = []
for y, row in enumerate(rows):
    x = 0
    while x < size:
        if row[x]:
            start = x
            while x < size and row[x]:
                x += 1
            d.append(f'M{start} {y}h{x - start}v1h-{x - start}z')
        else:
            x += 1

out = f"""/**
 * The QR code on the Fin NFC card preview: {URL}
 * Generated by scripts/make-qr.py (segno, error correction M) — do not edit by hand.
 * QR_PATH draws the dark modules on a {size} x {size} grid (no quiet zone; add one around it).
 */
export const QR_URL = '{URL}';
export const QR_SIZE = {size};
export const QR_PATH =
  '{''.join(d)}';
"""
(ROOT / 'src/brand/qr.ts').write_text(out, encoding='utf-8')
print(f'{URL}: version {qr.version}, {size} x {size} modules, {len(d)} runs')
